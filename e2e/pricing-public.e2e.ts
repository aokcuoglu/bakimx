import { expect, test } from "@playwright/test"

test("public pricing keeps prices and registration links in sync on desktop and mobile", async ({ page }, testInfo) => {
  await page.goto("/fiyatlar")
  // Radix makes the group tabbable once its client controls have mounted.
  await expect(page.getByRole("radiogroup", { name: "Faturalama dönemi" })).toHaveAttribute("tabindex", "0")
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
  const cards = page.getByRole("article")
  await expect(cards).toHaveCount(3)
  const pro = page.getByRole("article", { name: "Profesyonel" })
  await expect(pro).toContainText("₺1.799")
  await expect(pro.getByRole("link", { name: "Ücretsiz dene" })).toHaveAttribute("href", "/register?tier=pro&cycle=monthly")
  const yearly = page.getByRole("radio", { name: "Yıllık", exact: true })
  await yearly.click()
  await expect(yearly).toHaveAttribute("aria-checked", "true")
  await expect(pro).toContainText("₺17.990")
  await expect(pro).toContainText("Yıllık faturalandırılır")
  await expect(pro.getByRole("link", { name: "Ücretsiz dene" })).toHaveAttribute("href", "/register?tier=pro&cycle=yearly")
  await expect(page.getByRole("article", { name: "Premium", exact: true })).toContainText("₺29.990")
  await expect(page.getByRole("article", { name: "Lite", exact: true })).toContainText("0 TL")
  await yearly.focus()
  await yearly.press("ArrowLeft")
  await expect(page.getByRole("radio", { name: "Aylık", exact: true })).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(pro).toContainText("₺1.799")
  for (const width of [1440, 768, 390, 360]) {
    await page.setViewportSize({ width, height: 1000 })
    for (const card of await cards.all()) await expect(card).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await expect(page.getByRole("tab", { name: "Lite", exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Premium", exact: true }).click()
  await expect(page.getByRole("tabpanel")).toContainText("Yakında")
  await page.setViewportSize({ width: 1440, height: 1100 })
  await expect(page.getByRole("table")).toBeVisible()
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath("desktop.png") })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath("mobile.png") })
})

test("comparison header stays below navigation and shares the billing cycle", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("/fiyatlar")
  const table = page.getByRole("table", { name: "Paket özelliklerini karşılaştırın" })
  const period = table.getByRole("radiogroup", { name: "Karşılaştırma faturalama dönemi" })
  await expect(period).toHaveAttribute("tabindex", "0")
  await period.getByRole("radio", { name: "Yıllık", exact: true }).click()
  await expect(page.getByRole("article", { name: "Profesyonel" })).toContainText("₺17.990")
  await expect(table.getByRole("link", { name: "Ücretsiz dene" }).first()).toHaveAttribute("href", "/register?tier=pro&cycle=yearly")
  const header = table.locator("thead")
  const tableTop = await table.evaluate((element) => element.getBoundingClientRect().top + window.scrollY)
  await page.evaluate((y) => window.scrollTo({ top: y + 600, behavior: "instant" }), tableTop)
  const bounds = await header.boundingBox()
  expect(bounds?.y).toBeCloseTo(68, 0)
  await expect(period).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath("comparison-sticky.png") })
  await period.getByRole("radio", { name: "Aylık", exact: true }).click()
  await expect(table.getByRole("link", { name: "Ücretsiz dene" }).first()).toHaveAttribute("href", "/register?tier=pro&cycle=monthly")
  await expect(page.getByRole("article", { name: "Profesyonel" })).toContainText("₺1.799")
})

test("prices slide between periods and respect reduced motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/fiyatlar")
  const period = page.getByRole("radiogroup", { name: "Faturalama dönemi", exact: true })
  await expect(period).toHaveAttribute("tabindex", "0")
  const pro = page.getByRole("article", { name: "Profesyonel" })
  const roll = pro.locator('[data-slot="price-roll"]')
  const currency = pro.getByText("₺", { exact: true })
  const currencyBefore = await currency.boundingBox()
  const width = await roll.evaluate((element) => element.getBoundingClientRect().width)
  await period.getByRole("radio", { name: "Yıllık", exact: true }).click()
  await expect(roll).toHaveAttribute("data-cycle", "yearly")
  await expect(roll.locator(".sr-only")).toHaveText("17.990")
  await roll.evaluate(async (element) => {
    await Promise.all(element.getAnimations({ subtree: true }).map((animation) => animation.finished))
  })
  expect(await currency.boundingBox()).toEqual(currencyBefore)
  await expect(roll).not.toContainText("₺")
  const annual = roll.locator('[aria-hidden="true"]').last()
  expect(await annual.evaluate((element) => getComputedStyle(element).transform)).toBe("matrix(1, 0, 0, 1, 0, 0)")
  expect(await annual.evaluate((element) => getComputedStyle(element).transitionDuration)).toBe("0.36s")
  expect(await roll.evaluate((element) => element.getBoundingClientRect().width)).toBe(width)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await period.getByRole("radio", { name: "Aylık", exact: true }).click()
  await expect(roll.locator(".sr-only")).toHaveText("1.799")
  expect(await annual.evaluate((element) => getComputedStyle(element).transitionDuration)).toBe("0s")
  await expect(page.getByRole("article", { name: "Lite", exact: true }).locator('[data-slot="price-roll"]')).toHaveCount(0)
})
