import { expect, test } from "@playwright/test"

// #782: tek paket — Servis Paketi ₺1.499/ay, yıllık ₺14.990. Ek özellikler fiyatsız listelenir.
test("public pricing shows the single package with synced price and registration link on desktop and mobile", async ({ page }, testInfo) => {
  await page.goto("/fiyatlar")
  // Radix makes the group tabbable once its client controls have mounted.
  await expect(page.getByRole("radiogroup", { name: "Faturalama dönemi" })).toHaveAttribute("tabindex", "0")
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
  const cards = page.getByRole("article")
  await expect(cards).toHaveCount(1)
  const pkg = page.getByRole("article", { name: "Servis Paketi" })
  await expect(pkg).toContainText("₺1.499")
  await expect(pkg).toContainText("5 kullanıcı dahil")
  await expect(pkg.getByRole("link", { name: "Ücretsiz dene" })).toHaveAttribute("href", "/register?tier=pro&cycle=monthly")
  const yearly = page.getByRole("radio", { name: /Yıllık/ })
  await yearly.click()
  await expect(yearly).toHaveAttribute("aria-checked", "true")
  await expect(pkg).toContainText("₺14.990")
  await expect(pkg).toContainText("yıllık faturalandırılır")
  await expect(pkg.getByRole("link", { name: "Ücretsiz dene" })).toHaveAttribute("href", "/register?tier=pro&cycle=yearly")
  await yearly.focus()
  await yearly.press("ArrowLeft")
  await expect(page.getByRole("radio", { name: "Aylık", exact: true })).toBeFocused()
  await page.keyboard.press("Enter")
  await expect(pkg).toContainText("₺1.499")
  for (const width of [1440, 768, 390, 360]) {
    await page.setViewportSize({ width, height: 1000 })
    await expect(pkg).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  }
  await expect(page.getByRole("tab", { name: "Pakete dahil", exact: true })).toBeVisible()
  await page.getByRole("tab", { name: "Ek özellikler", exact: true }).click()
  const addons = page.getByRole("tabpanel")
  await expect(addons).toContainText("Şaseden parça")
  await expect(addons).toContainText("Ruhsat OCR")
  await expect(addons).toContainText("Yakında")
  await expect(addons).not.toContainText("₺")
  await page.setViewportSize({ width: 1440, height: 1100 })
  const included = page.getByRole("table", { name: "Pakete dahil olanlar" })
  await expect(included).toBeVisible()
  await expect(included).toContainText("Plaka okuma")
  await expect(included).not.toContainText("Ruhsat OCR")
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath("desktop.png") })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.evaluate(() => window.scrollTo(0, 0))
  await page.screenshot({ path: testInfo.outputPath("mobile.png") })
})

test("desktop lists add-ons without prices and never links to a removed tier", async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto("/fiyatlar")
  const addons = page.getByRole("region", { name: "Pakete dahil olmayan ek özellikler" }).filter({ visible: true })
  await expect(addons).toBeVisible()
  for (const name of ["Şaseden parça", "AI danışmanı", "Ruhsat OCR", "e-Fatura", "Çoklu şube"]) {
    await expect(addons).toContainText(name)
  }
  await expect(addons).not.toContainText("₺")
  await expect(page.locator('a[href*="tier=lite"], a[href*="tier=premium"], a[href*="/checkout"]')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath("addons-desktop.png") })
})

test("prices slide between periods and respect reduced motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "no-preference" })
  await page.goto("/fiyatlar")
  const period = page.getByRole("radiogroup", { name: "Faturalama dönemi", exact: true })
  await expect(period).toHaveAttribute("tabindex", "0")
  const pkg = page.getByRole("article", { name: "Servis Paketi" })
  const roll = pkg.locator('[data-slot="price-roll"]')
  const currency = pkg.getByText("₺", { exact: true })
  const currencyBefore = await currency.boundingBox()
  const width = await roll.evaluate((element) => element.getBoundingClientRect().width)
  await period.getByRole("radio", { name: /Yıllık/ }).click()
  await expect(roll).toHaveAttribute("data-cycle", "yearly")
  await expect(roll.locator(".sr-only")).toHaveText("14.990")
  await roll.evaluate(async (element) => {
    await Promise.all(element.getAnimations({ subtree: true }).map((animation) => animation.finished))
  })
  expect(await currency.boundingBox()).toEqual(currencyBefore)
  await expect(roll).not.toContainText("₺")
  const annual = roll.locator('[aria-hidden="true"]').last()
  expect(await annual.evaluate((element) => getComputedStyle(element).transform)).toBe("matrix(1, 0, 0, 1, 0, 0)")
  expect(await annual.evaluate((element) => getComputedStyle(element).transitionDuration)).toBe("0.6s")
  expect(await roll.evaluate((element) => element.getBoundingClientRect().width)).toBe(width)
  await page.emulateMedia({ reducedMotion: "reduce" })
  await period.getByRole("radio", { name: "Aylık", exact: true }).click()
  await expect(roll.locator(".sr-only")).toHaveText("1.499")
  expect(await annual.evaluate((element) => getComputedStyle(element).transitionDuration)).toBe("0s")
})
