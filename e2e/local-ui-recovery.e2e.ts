import { expect, test } from "@playwright/test"

for (const width of [390, 1440]) {
  test(`recovered admin controls at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/api/auth/dev-login?email=admin@bakimx.com&redirect=/admin/workshops")
    const workshop = page.locator('a[href^="/admin/workshops/"]').first()
    await expect(workshop).toBeVisible()
    const href = await workshop.getAttribute("href")
    await page.goto(`${href}?from=2026-09-10`)
    const openRange = page.getByRole("button", { name: "10.09.2026 – …", exact: true })
    await expect(openRange).toBeVisible()
    await openRange.focus()
    await page.keyboard.press("Enter")
    const popup = page.getByRole("dialog", { name: "Tarih aralığı seçimi" })
    await expect(popup).toBeVisible()
    await expect(popup.getByRole("combobox")).toHaveCount(2)
    await popup.getByRole("button", { name: "Tamam", exact: true }).click()
    await expect(popup).toBeHidden()
    await expect(openRange).toBeFocused()
    await openRange.click()
    await popup.getByRole("button", { name: "Temizle", exact: true }).click()
    const usageForm = page.locator("form").filter({ hasText: "Tarih aralığı" }).first()
    const emptyRange = usageForm.getByRole("button", { name: "Tüm zamanlar", exact: true })
    await expect(emptyRange).toBeVisible()
    await emptyRange.click()
    await popup.getByRole("combobox").nth(1).selectOption("1950")
    await expect(popup.getByRole("combobox").nth(1)).toHaveValue("1950")
    await popup.getByRole("combobox").nth(0).selectOption("0")
    await expect(popup.getByRole("combobox").nth(0)).toHaveValue("0")
    await expect(emptyRange).toHaveText(/Tüm zamanlar/)
    const days = popup.locator('[data-day]')
    await days.filter({ hasText: /^10$/ }).first().click()
    await expect(popup).toBeVisible()
    await days.filter({ hasText: /^11$/ }).first().click()
    await expect(popup).toBeHidden()
    await expect(page.getByRole("button", { name: "10.01.1950 – 11.01.1950", exact: true })).toBeVisible()

    await page.goto(`${href}?from=2026-09-10&to=2026-09-10`)
    const sameDay = page.getByRole("button", { name: "10.09.2026", exact: true })
    await expect(sameDay).toBeVisible()
    await sameDay.click()
    await page.keyboard.press("Escape")
    await expect(sameDay).toBeFocused()
    await page.goto(`${href}?to=2026-09-10`)
    await expect(page.getByRole("button", { name: "… – 10.09.2026", exact: true })).toBeVisible()

    await page.goto(`${href}?from=1900-01-10`)
    const historicalRange = page.getByRole("button", { name: "10.01.1900 – …", exact: true })
    await historicalRange.click()
    await expect(popup.getByRole("combobox").nth(1)).toHaveValue("1900")
    await popup.getByRole("combobox").nth(1).selectOption("1890")
    await popup.getByRole("button", { name: "Tamam", exact: true }).click()
    await expect(historicalRange).toBeVisible()

    await page.goto(`${href}?orderFrom=2026-09-10`)
    const orderForm = page.locator("form").filter({ hasText: "Tarih aralığı" }).nth(1)
    await orderForm.getByRole("button", { name: "10.09.2026 – …", exact: true }).click()
    await popup.getByRole("button", { name: "Temizle", exact: true }).click()
    await expect(orderForm.getByRole("button", { name: "Tüm zamanlar", exact: true })).toBeVisible()

    await page.goto("/admin/catalog")
    const scrollArea = page.getByRole("region", { name: "Ürün listesi" })
    await expect(scrollArea).toHaveCount(1)
    await scrollArea.focus()
    await expect(scrollArea).toBeFocused()
    await expect(scrollArea).toHaveCSS("max-height", "644px")
    await expect(scrollArea).toHaveCSS("overflow-y", "auto")
    const box = await scrollArea.boundingBox()
    expect(box?.height).toBeLessThanOrEqual(646)
  })
}
