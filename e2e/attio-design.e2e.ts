import { expect, test } from "@playwright/test"

for (const width of [320, 390, 768, 1440]) {
  test(`record patterns preserve navigation and modal focus at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/design')
    const patterns = page.getByTestId('record-patterns')
    await patterns.scrollIntoViewIfNeeded()
    const overview = patterns.getByRole('tab', { name: 'Genel bakış' })
    await expect(overview).toHaveAttribute('aria-selected', 'true')
    const style = await overview.evaluate(e => {
      const s = getComputedStyle(e), line = getComputedStyle(e, '::after')
      return { font: s.fontFamily, size: s.fontSize, radius: s.borderRadius, border: s.borderTopStyle, underline: line.opacity, height: line.height }
    })
    expect(style.font).toContain('Inter')
    expect(style.size).toBe('14px')
    expect(style.radius).toBe('8px')
    expect(style.border).toBe('solid')
    expect(style.underline).toBe('1')
    expect(style.height).toBe('1px')
    await overview.focus()
    await page.keyboard.press('ArrowRight')
    await expect(patterns.getByRole('tab', { name: 'Hareketler' })).toBeFocused()
    await expect(patterns.getByRole('tab', { name: 'Hareketler' })).toHaveAttribute('aria-selected', 'true')
    await page.keyboard.press('Home')
    await expect(overview).toBeFocused()
    await expect(patterns.locator('[data-slot="highlight-card"]')).toHaveCount(6)
    const trigger = patterns.getByRole('button', { name: 'Randevu örneği' })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'Yeni randevu' })
    await expect(dialog).toBeVisible()
    await expect(dialog).toHaveCSS('border-radius', '16px')
    expect(await dialog.evaluate(e => getComputedStyle(e).boxShadow)).not.toBe('none')
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(bounds!.height).toBeLessThanOrEqual(900)
    await expect(dialog.getByLabel('Randevu başlığı')).toBeFocused()
    await dialog.getByRole('button', { name: 'Önizlemeyi tamamla' }).click()
    await expect(dialog.getByText('Bir başlık girin.')).toBeVisible()
    await dialog.getByLabel('Randevu başlığı').fill('Örnek randevu')
    await dialog.getByRole('combobox').click()
    await expect(page.getByRole('option', { name: '1 saat' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByLabel('Randevu başlığı')).toHaveValue('Örnek randevu')
    await page.keyboard.press('Escape')
    await expect(dialog).toBeHidden()
    await expect(trigger).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

test('dialog fits short viewports with reduced motion and dark surfaces', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 500 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/design')
  await page.evaluate(() => document.documentElement.classList.add('dark'))
  await page.getByRole('button', { name: 'Randevu örneği' }).click()
  const dialog = page.getByRole('dialog', { name: 'Yeni randevu' })
  await expect(dialog).toBeVisible()
  const styles = await dialog.evaluate(e => ({ animation: getComputedStyle(e).animationName, overflow: getComputedStyle(e).overflowY, height: e.getBoundingClientRect().height }))
  expect(styles.animation).toBe('none')
  expect(styles.overflow).toBe('auto')
  expect(styles.height).toBeLessThanOrEqual(468)
  await dialog.getByRole('button', { name: 'Vazgeç' }).click()
  await expect(dialog).toBeHidden()
})
