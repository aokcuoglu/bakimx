import { expect, test } from "@playwright/test"

for (const width of [320, 390, 768, 1440]) {
  test(`Attio search palette fits and keeps its action reachable at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/api/auth/dev-login?redirect=/dashboard")
    await page.keyboard.press("Control+k")
    const dialog = page.getByRole("dialog", { name: "Genel arama" })
    const search = dialog.getByRole("combobox")
    await expect(search).toBeFocused()
    await expect(search).toHaveCSS("font-size", "16px")
    await expect.poll(async () => (await dialog.boundingBox())?.width).toBe(Math.min(width - 24, 742))
    const bounds = await dialog.boundingBox()
    expect(bounds).not.toBeNull()
    expect(bounds!.x).toBeGreaterThanOrEqual(8)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width - 8)
    expect(bounds!.y + bounds!.height).toBeLessThan(900)
    if (width >= 768) expect(bounds!.width).toBe(742)
    await expect(dialog.getByRole("option", { name: "Kayıtlarda ara" })).toHaveCSS("height", "36px")
    const results = dialog.getByRole("listbox")
    await results.evaluate((element) => { element.scrollTop = element.scrollHeight })
    await expect(dialog.getByRole("button", { name: "Kayıtlarda ara", exact: true })).toBeInViewport()
    await search.fill("Faturalandırma")
    await expect(dialog.getByRole("option", { name: "Faturalandırma" })).toHaveAttribute("aria-selected", "true")
    await dialog.getByRole("button", { name: "Faturalandırma", exact: true }).click()
    await expect(page).toHaveURL(/\/settings\/billing$/)
  })
}

test("footer follows keyboard selection and enters record search", async ({ page }) => {
  await page.goto("/api/auth/dev-login?redirect=/dashboard")
  await page.keyboard.press("Control+k")
  const dialog = page.getByRole("dialog", { name: "Genel arama" })
  const search = dialog.getByRole("combobox")
  await search.press("ArrowDown")
  await expect(dialog.getByRole("button", { name: "Yeni iş emri", exact: true })).toBeVisible()
  await search.press("ArrowUp")
  await dialog.getByRole("button", { name: "Kayıtlarda ara", exact: true }).click()
  await expect(search).toBeFocused()
  await expect(search).toHaveAttribute("placeholder", "Müşteri, araç veya iş emri ara...")
  await expect(dialog.getByRole("button", { name: "Kayıtlarda ara", exact: true })).toHaveCount(0)
  await search.press("Escape")
  await expect(dialog).toHaveCount(0)
})
